#!/usr/bin/env node
/**
 * Writes oracle/CARD-PROGRESS.md: which of the sixty-four are written and which
 * are not, with a tick by each. Adrian, 2026-09-22: "have a file that says which
 * ones are written, which ones are not, with little check marks by them, so when
 * I have credits I can go through the rest of them."
 *
 * It is generated, never hand-edited, so it cannot drift from the cards. Two
 * measurements, both read off the files:
 *   SECTIONS  the sentence check's gating count for the card. A card through the
 *             pass reads 0. An untouched one reads 40 to 70.
 *   ENTRANCE  whether meta.centre is the settled sentence for that card, taken
 *             from todo/plans/writing-guideline/entrance-openings.md.
 * Run: npm run progress
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const CARDS = 'oracle/cards';
const PLAN = 'todo/plans/writing-guideline/entrance-openings.md';
const OUT = 'oracle/CARD-PROGRESS.md';

const settled = new Map();
for (const line of readFileSync(PLAN, 'utf8').split('\n')) {
  const m = line.match(/^(\d{2}) · (.+?)\s\s\((.+)\)\s*$/);
  if (m) settled.set(m[1], { text: m[2].trim(), title: m[3] });
}

const rows = [];
for (const f of readdirSync(CARDS).filter((x) => /^\d\d\.md$/.test(x)).sort()) {
  const id = f.slice(0, 2);
  const raw = readFileSync(`${CARDS}/${f}`, 'utf8');
  const title = (raw.match(/^card_name:\s*(.+)$/m) || [, '?'])[1].trim();
  const centre = (raw.match(/^\s{2}centre:\s*"([^"]*)"/m) || [, ''])[1];
  let gating = null;
  try {
    execFileSync('node', ['todo/plans/writing-guideline/sentence-check.mjs', `${CARDS}/${f}`], { encoding: 'utf8' });
    gating = 0;
  } catch (e) {
    const out = (e.stdout || '') + (e.stderr || '');
    const m = out.match(/(\d+) gating/);
    gating = m ? Number(m[1]) : null;
  }
  const want = settled.get(id);
  const entranceDone = Boolean(want && centre && centre.startsWith(want.text.split('.')[0]));
  rows.push({ id, title, gating, entranceDone, hasEntrance: Boolean(want) });
}

const tick = (b) => (b ? 'x' : ' ');
const done = rows.filter((r) => r.gating === 0 && r.entranceDone);
const started = rows.filter((r) => !(r.gating === 0 && r.entranceDone) && (r.gating === 0 || r.entranceDone));
const todo = rows.filter((r) => r.gating !== 0 && !r.entranceDone);

const lines = [];
lines.push('# The sixty-four: what is written');
lines.push('');
lines.push(`Generated by \`npm run progress\`, last run ${new Date().toISOString().slice(0, 10)}. Never edit by hand: it is`);
lines.push('read off the cards themselves, so it cannot drift.');
lines.push('');
lines.push('A card is **written** when both hold. **Sections**: the sentence check finds nothing');
lines.push('to gate, which a card only reaches by going through the pass. **Entrance**: the card');
lines.push('carries its settled opening sentence, the one agreed with Adrian.');
lines.push('');
lines.push(`**${done.length} written. ${started.length} part way. ${todo.length} not started.**`);
lines.push('');
lines.push('One writer per card, sections first and the entrance last: see [dispatching a card writer](ENTRANCE-DISPATCH.md).');
lines.push('');
const block = (name, list, note) => {
  lines.push(`## ${name} (${list.length})`);
  if (note) { lines.push(''); lines.push(note); }
  lines.push('');
  for (const r of list) {
    const bits = [];
    bits.push(`sections ${r.gating === 0 ? 'done' : `${r.gating} to fix`}`);
    bits.push(`entrance ${r.entranceDone ? 'in' : r.hasEntrance ? 'settled, not in the card' : 'not settled'}`);
    lines.push(`- [${tick(r.gating === 0 && r.entranceDone)}] **${r.id} ${r.title}** · ${bits.join(' · ')}`);
  }
  lines.push('');
};
block('Written', done, 'Nothing to do on these but read them.');
block('Part way', started, 'One half is done. The line after each says which.');
block('Not started', todo, 'Each takes one writer, one pass, about ten minutes of machine time.');
writeFileSync(OUT, lines.join('\n') + '\n');
console.log(`${OUT}: ${done.length} written, ${started.length} part way, ${todo.length} not started`);
