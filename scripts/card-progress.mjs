#!/usr/bin/env node
/**
 * Writes oracle/CARD-PROGRESS.md: which of the sixty-four are written and which
 * are not, with a tick by each. Adrian, 2026-09-22: "have a file that says which
 * ones are written, which ones are not, with little check marks by them, so when
 * I have credits I can go through the rest of them."
 *
 * It is generated, never hand-edited, so it cannot drift from the cards. Two
 * measurements, both read off the files:
 *   SECTIONS  the sentence check's gating count for the card. A card through the
 *             pass reads 0. An untouched one reads 40 to 70.
 *   ENTRANCE  whether meta.centre is the settled sentence for that card, taken
 *             from todo/plans/writing-guideline/entrance-openings.md.
 *   YOURS     whether every section's status says final. Final is Adrian's
 *             editorial decision and never an automated score (GUIDELINE.md),
 *             so no script sets it and no card reads 100% without it.
 * Run: npm run progress
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const CARDS = 'oracle/cards';
const PLAN = 'todo/plans/writing-guideline/entrance-openings.md';
const OUT = 'oracle/CARD-PROGRESS.md';

const settled = new Map();
for (const line of readFileSync(PLAN, 'utf8').split('\n')) {
  const m = line.match(/^(\d{2}) · (.+?)\s\s\((.+)\)\s*$/);
  if (m) settled.set(m[1], { text: m[2].trim(), title: m[3] });
}

const HOWTO = readFileSync('oracle/.progress-howto.md', 'utf8');

const rows = [];
for (const f of readdirSync(CARDS).filter((x) => /^\d\d\.md$/.test(x)).sort()) {
  const id = f.slice(0, 2);
  const raw = readFileSync(`${CARDS}/${f}`, 'utf8');
  const title = (raw.match(/^card_name:\s*(.+)$/m) || [, '?'])[1].trim();
  const centre = (raw.match(/^\s{2}centre:\s*"([^"]*)"/m) || [, ''])[1];
  let gating = null;
  try {
    execFileSync('node', ['todo/plans/writing-guideline/sentence-check.mjs', `${CARDS}/${f}`], { encoding: 'utf8' });
    gating = 0;
  } catch (e) {
    const out = (e.stdout || '') + (e.stderr || '');
    const m = out.match(/(\d+) gating/);
    gating = m ? Number(m[1]) : null;
  }
  const want = settled.get(id);
  const entranceDone = Boolean(want && centre && centre.startsWith(want.text.split('.')[0]));
  const block = (raw.match(/^status:\n((?:\s{2}\w+:\s*\S+\n)+)/m) || [, ''])[1];
  const marks = block.trim().split('\n').map((l) => l.split(':')[1].trim()).filter(Boolean);
  const yours = marks.length > 0 && marks.every((m) => m === 'final');
  // The gate (scripts/card-gate.mjs) is the framework and the checks after. A card
  // whose sentences pass but whose gate does not is part way, not written.
  let gate = false;
  if (gating === 0) {
    try { execFileSync('node', ['scripts/card-gate.mjs', id], { stdio: 'ignore' }); gate = true; } catch { gate = false; }
  }
  rows.push({ id, title, gating, gate, entranceDone, hasEntrance: Boolean(want), yours });
}

const tick = (b) => (b ? 'x' : ' ');
const ready = (r) => r.gating === 0 && r.gate;
const finished = rows.filter((r) => ready(r) && r.yours);
const done = rows.filter((r) => ready(r) && !r.yours);
const started = rows.filter((r) => !ready(r) && (r.gating === 0 || r.entranceDone));
const todo = rows.filter((r) => r.gating !== 0 && !r.entranceDone);

const lines = [];
lines.push('# The sixty-four: what is written');
lines.push('');
lines.push(`Generated by \`npm run progress\`, last run ${new Date().toISOString().slice(0, 10)}. Never edit by hand: it is`);
lines.push('read off the cards themselves, so it cannot drift.');
lines.push('');
lines.push(HOWTO.trimEnd());
lines.push('');
lines.push('Three states, and a card is only 100% when all three hold.');
lines.push('');
lines.push('1. **Sections written**: the sentence check finds nothing to gate, which a card only');
lines.push('   reaches by going through the pass.');
lines.push('2. **Through the gate**: `npm run card:gate -- NN` passes. That means the worksheet was filled');
lines.push('   BEFORE writing (the energy whole, the true things, the allotment), the entrance and CODE');
lines.push('   do not name the energy by its shadow, and every reader check and the cold reader are done.');
lines.push('   See [the worksheet](WORKSHEET.md). A sentence on file is a draft until it passes this.');
lines.push('3. **Adrian\'s yes**: every section\'s status says `final`. That is his editorial decision');
lines.push('   and never an automated score, so no script sets it and no writer may set it.');
lines.push('');
lines.push(`**${finished.length} finished. ${done.length} written, waiting on Adrian. ${started.length} part way. ${todo.length} not started.**`);
lines.push('');
lines.push('One writer per card, sections first and the entrance last: see [dispatching a card writer](CARD-PASS.md).');
lines.push('');
const block = (name, list, note) => {
  lines.push(`## ${name} (${list.length})`);
  if (note) { lines.push(''); lines.push(note); }
  lines.push('');
  for (const r of list) {
    const bits = [];
    bits.push(`sections ${r.gating === 0 ? 'done' : `${r.gating} to fix`}`);
    bits.push(`entrance ${r.entranceDone ? 'in' : r.hasEntrance ? 'drafted, not in the card' : 'not drafted'}`);
    if (r.gating === 0) bits.push(r.gate ? 'through the gate' : 'gate not passed');
    if (ready(r)) bits.push(r.yours ? 'yours' : 'waiting on you');
    lines.push(`- [${tick(ready(r) && r.yours)}] **${r.id} ${r.title}** · ${bits.join(' · ')}`);
  }
  lines.push('');
};
block('Finished', finished, 'Written, and you have said yes. Nothing left on these.');
block('Written, waiting on you', done, 'Read it on the page. If it holds, its status goes to final and it moves up.');
block('Part way', started, 'One half is done. The line after each says which.');
block('Not started', todo, 'Each takes one writer, one pass, about ten minutes of machine time.');
writeFileSync(OUT, lines.join('\n') + '\n');
console.log(`${OUT}: ${finished.length} finished, ${done.length} waiting on Adrian, ${started.length} part way, ${todo.length} not started`);
